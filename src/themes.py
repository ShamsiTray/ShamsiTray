# The registry every consumer reads (config.py): slug -> palette, in file
# order. The slug is the settings key persisted under Appearance/ThemeChoice
# and the gallery's identifier ("DRACULA_PALETTE" -> "dracula",
# "NORD_LIGHT_PALETTE" -> "nord_light"). A duplicate attribute name would be
# a redefinition this module's own linting flags, so a slug can never be
# silently shadowed the way the old multi-pack loader allowed.
THEMES = {
    _name[:-len("_PALETTE")].lower(): _value
    for _name, _value in list(globals().items())
    if _name.isupper() and _name.endswith("_PALETTE")
}

